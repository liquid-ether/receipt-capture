// Builds the Material Design 3 assets the web app serves.
//
//   cd tools/material && npm ci && npm run build
//
// Everything lands in src/ReceiptCapture.Web/wwwroot and is committed. The app is
// served as static files with no build step, and nothing is fetched from a CDN at
// runtime: a receipt capture page that phones a third party every time it loads
// would be leaking when and where someone shops.
//
// Outputs:
//   lib/material.js              the Material Web components, bundled
//   lib/THIRD_PARTY_NOTICES.txt  licenses of everything bundled or copied
//   css/theme.css                the M3 colour scheme, light and dark
//   css/fonts.css, fonts/*       Roboto, self-hosted
//   icons/symbols.svg            the Material Symbols the UI uses, as a sprite

import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const wwwroot = resolve(here, '../../src/ReceiptCapture.Web/wwwroot');
const modules = join(here, 'node_modules');

/** The brand colour everything else is derived from. */
const SEED = '#1F6F54';

/**
 * Icons the markup and script reference by id. Adding one means adding it here.
 * The "-fill" variants are for the selected navigation destination, which M3 marks
 * with a filled icon inside the active indicator.
 */
const ICONS = [
  'add', 'close', 'delete', 'error', 'history', 'history-fill', 'lock', 'logout',
  'photo_camera', 'photo_camera-fill', 'photo_library', 'receipt_long', 'refresh',
  'send', 'settings', 'settings-fill', 'translate', 'warning',
];

async function main() {
  const bundled = await bundleComponents();
  await writeTheme();
  const fontFiles = await copyFonts();
  await writeIconSprite();
  await writeNotices(bundled);

  console.log(`material.js, theme.css, ${fontFiles} font files, ${ICONS.length} icons, notices`);
}

/* ------------------------------------------------------------- components */

async function bundleComponents() {
  const out = join(wwwroot, 'lib', 'material.js');
  await mkdir(dirname(out), { recursive: true });

  const result = await build({
    entryPoints: [join(here, 'entry.js')],
    bundle: true,
    format: 'esm',
    minify: true,
    // iOS 15 is the oldest Safari still receiving security updates.
    target: ['es2021', 'safari15'],
    legalComments: 'none', // licenses ship in THIRD_PARTY_NOTICES.txt instead
    metafile: true,
    outfile: out,
    logLevel: 'warning',
  });

  // Every package that contributed code, so the notices cover exactly what ships.
  const packages = new Set();
  for (const input of Object.keys(result.metafile.inputs)) {
    const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
    if (match) packages.add(match[1]);
  }
  return packages;
}

/* ------------------------------------------------------------------ theme */

async function writeTheme() {
  // material-color-utilities ships extensionless ESM imports that Node cannot
  // resolve on its own, so it goes through esbuild too.
  const bundle = await build({
    stdin: {
      contents: `export * from '@material/material-color-utilities';`,
      resolveDir: here,
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    write: false,
    logLevel: 'warning',
  });
  const temp = join(here, '.color-utils.mjs');
  await writeFile(temp, bundle.outputFiles[0].text);

  try {
    const { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors } =
      await import(pathToFileURL(temp).href);

    const roles = Object.getOwnPropertyNames(MaterialDynamicColors)
      .filter((name) => typeof MaterialDynamicColors[name]?.getArgb === 'function')
      // Key colours are palette anchors, not roles a component paints with.
      .filter((name) => !name.endsWith('PaletteKeyColor'))
      .sort();

    const block = (isDark) => {
      const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
      return roles
        .map((name) => `  --md-sys-color-${kebab(name)}: ${hexFromArgb(MaterialDynamicColors[name].getArgb(scheme))};`)
        .join('\n');
    };

    const css = `/*
 * Material Design 3 colour scheme, generated by tools/material/build.mjs from the
 * seed ${SEED} with the tonal-spot scheme. Do not edit by hand; change SEED and
 * rebuild instead, so light and dark stay derived from the same palette.
 */

:root {
  color-scheme: light dark;
  --md-ref-typeface-brand: 'Roboto', system-ui, sans-serif;
  --md-ref-typeface-plain: 'Roboto', system-ui, sans-serif;
${block(false)}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(true).replace(/^/gm, '  ')}
  }
}
`;

    await mkdir(join(wwwroot, 'css'), { recursive: true });
    await writeFile(join(wwwroot, 'css', 'theme.css'), css);
  } finally {
    await rm(temp, { force: true });
  }
}

function kebab(name) {
  return name.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase());
}

/* ------------------------------------------------------------------ fonts */

async function copyFonts() {
  const source = join(modules, '@fontsource', 'roboto');
  const target = join(wwwroot, 'fonts');
  await mkdir(target, { recursive: true });

  // Latin covers English and French, including every accent French uses;
  // latin-ext covers the rest of Western Europe for merchant names.
  //
  // The faces come from the combined per-weight stylesheet, not the per-subset
  // ones: only the combined file carries unicode-range, and without it two faces
  // with the same family and weight simply replace each other.
  const faces = [];
  let copied = 0;
  for (const weight of [400, 500]) {
    const css = await readFile(join(source, `${weight}.css`), 'utf8');

    for (const subset of ['latin', 'latin-ext']) {
      const marker = `/* roboto-${subset}-${weight}-normal */`;
      const start = css.indexOf(marker);
      if (start < 0) throw new Error(`no ${subset} ${weight} face in @fontsource/roboto`);

      const face = css.slice(start, css.indexOf('}', start) + 1);
      if (!face.includes('unicode-range')) throw new Error(`${subset} ${weight} face has no unicode-range`);
      faces.push(face.replace(/url\(\.\/files\//g, 'url(/fonts/'));

      const file = `roboto-${subset}-${weight}-normal.woff2`;
      await copyFile(join(source, 'files', file), join(target, file));
      copied += 1;
    }
  }

  const header = `/* Roboto, self-hosted from @fontsource/roboto. Generated by tools/material/build.mjs. */\n\n`;
  // Only woff2 is copied; every browser that runs this app supports it.
  const woff2Only = faces
    .join('\n\n')
    .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '');
  await writeFile(join(wwwroot, 'css', 'fonts.css'), header + woff2Only + '\n');

  return copied;
}

/* ------------------------------------------------------------------ icons */

async function writeIconSprite() {
  const source = join(modules, '@material-symbols', 'svg-400', 'outlined');
  const symbols = [];

  for (const name of [...ICONS].sort()) {
    const svg = await readFile(join(source, `${name}.svg`), 'utf8');
    const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 -960 960 960';
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    symbols.push(`  <symbol id="${name}" viewBox="${viewBox}">${body}</symbol>`);
  }

  const sprite = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Material Symbols (outlined, weight 400), generated by tools/material/build.mjs. -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols.join('\n')}
</svg>
`;
  await writeFile(join(wwwroot, 'icons', 'symbols.svg'), sprite);
}

/* ---------------------------------------------------------------- notices */

async function writeNotices(bundledPackages) {
  const shipped = new Set([...bundledPackages, '@fontsource/roboto', '@material-symbols/svg-400']);
  const sections = [];

  for (const name of [...shipped].sort()) {
    const dir = join(modules, name);
    const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
    const licenseFile = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license']
      .map((file) => join(dir, file))
      .find((path) => existsSync(path));

    const text = licenseFile ? (await readFile(licenseFile, 'utf8')).trim() : `License: ${pkg.license}`;
    sections.push(`${name} ${pkg.version} (${pkg.license})\n${'-'.repeat(72)}\n${text}`);
  }

  const notices = `Third-party software served by Receipt Capture.
Generated by tools/material/build.mjs.

${sections.join('\n\n\n')}
`;
  await writeFile(join(wwwroot, 'lib', 'THIRD_PARTY_NOTICES.txt'), notices);
}

await main();
